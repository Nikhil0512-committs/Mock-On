interface I18nStore {
  currentLanguage: string;
  setLanguage: (code: string) => void;
  t: (key: string, defaultText?: string) => string;
}

const getSavedLanguage = (): string => {
  try {
    return localStorage.getItem("mock_on_language") || "en";
  } catch {
    return "en";
  }
};

export const useI18n = create<I18nStore>((set, get) => ({
  currentLanguage: getSavedLanguage(),
  setLanguage: (code: string) => {
    try {
      localStorage.setItem("mock_on_language", code);
    } catch {}
    set({ currentLanguage: code });
  },
  t: (key: string, defaultText?: string) => {
    const lang = get().currentLanguage;
    const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    const enDict = TRANSLATIONS.en;
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return defaultText || key;
  },
}));

/**
 * Convenient standalone translator function
 */
export function translate(key: string, defaultText?: string): string {
  return useI18n.getState().t(key, defaultText);
}

